"""Pydantic v2 schemas for Phase 4 Runtime SDK APIs:
Chat Router, Flow Stitcher, RAG, Self-Healing Resolver, and Telemetry Events.
"""

from __future__ import annotations

import uuid
from typing import Any, Literal
from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# SDK Chat Schemas
# ---------------------------------------------------------------------------

class AuthStateIn(BaseModel):
    is_logged_in: bool = False
    role: str | None = None


class SDKChatRequest(BaseModel):
    visitor_id: str = Field(description="Unique client-generated visitor identifier")
    session_id: uuid.UUID | None = Field(default=None, description="Optional existing chat session UUID")
    message: str = Field(min_length=1, max_length=2000, description="End-user chat message")
    locale: str = Field(default="en", description="Target language / locale code, e.g. en or hi")
    current_path: str = Field(default="/", description="Current page path where the user opened the chat")
    auth_state: AuthStateIn = Field(default_factory=AuthStateIn)


class StitchedWorkflowStep(BaseModel):
    execution_index: int
    step_id: uuid.UUID
    feature_slug: str
    step_order: int
    guide_id: str | None = None
    route_pattern: str
    action_type: str
    advance_on: str
    is_optional: bool = False
    wait_timeout_ms: int = 5000
    condition: dict | None = None
    content: dict = Field(default_factory=dict)
    target_fingerprint: dict = Field(default_factory=dict)


class ChainedFeatureSummary(BaseModel):
    feature_id: uuid.UUID
    slug: str
    title: str
    version_number: int
    is_prerequisite: bool = False


class TourPlan(BaseModel):
    target_feature_slug: str
    requires_login_first: bool = False
    role_warning: str | None = None
    chained_features: list[ChainedFeatureSummary] = Field(default_factory=list)
    steps: list[StitchedWorkflowStep] = Field(default_factory=list)


class RetrievedChunkInfo(BaseModel):
    chunk_id: uuid.UUID
    source_title: str
    content_preview: str
    score: float


class SDKChatResponse(BaseModel):
    session_id: uuid.UUID
    message_id: uuid.UUID
    reply: str
    route_taken: Literal["feature_match", "rag_answer", "out_of_scope", "smalltalk"]
    similarity: float | None = None
    matched_feature_slug: str | None = None
    tour_plan: TourPlan | None = None
    suggested_tour_plan: TourPlan | None = None
    retrieved_chunks: list[RetrievedChunkInfo] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# SDK Self-Healing Resolver Schemas
# ---------------------------------------------------------------------------

class CandidateIn(BaseModel):
    candidate_id: str = Field(description="Temporary client-side candidate identifier")
    tag: str = Field(description="HTML tag name, e.g. button, input, a")
    role: str | None = Field(default=None, description="Explicit or inferred ARIA role")
    text: str | None = Field(default=None, description="Visible inner text of the element")
    accessible_name: str | None = Field(default=None, description="Computed accessible name or aria-label")
    css_selector: str = Field(description="Unique CSS selector generated by the browser SDK")
    attrs: dict[str, Any] = Field(default_factory=dict, description="Attributes map, e.g. data-testid, id, name")
    landmark: str | None = Field(default=None, description="Containing landmark or region selector")


class SDKHealRequest(BaseModel):
    step_id: uuid.UUID = Field(description="Workflow step that failed primary and fingerprint locators")
    page_path: str = Field(description="Current page path where healing was attempted")
    dom_hash: str | None = Field(default=None, description="Optional SHA256 of visible interactive candidates")
    locale: str = Field(default="en", description="User locale")
    candidates: list[CandidateIn] = Field(default_factory=list, description="Visible candidates pruned by SDK")


class SDKHealResponse(BaseModel):
    status: Literal["cache_hit", "healed_by_ai", "fallback_to_text"]
    step_id: uuid.UUID
    resolved_candidate: dict | None = None
    suggested_selector: str | None = None
    confidence: float
    fallback_text: str | None = None


# ---------------------------------------------------------------------------
# SDK Telemetry / Events Batch Schemas
# ---------------------------------------------------------------------------

class TourEventIn(BaseModel):
    feature_version_id: uuid.UUID | None = None
    step_id: uuid.UUID | None = None
    event_type: Literal[
        "started",
        "step_shown",
        "step_completed",
        "completed",
        "exited",
        "failed",
    ]


class ResolutionLogIn(BaseModel):
    step_id: uuid.UUID
    status: Literal[
        "matched_primary",
        "matched_fingerprint",
        "healed_by_ai",
        "fallback_to_text",
        "cache_hit",
    ]
    resolution_ms: int | None = None
    page_path: str | None = None
    dom_hash: str | None = None
    detected_dom_selector: str | None = None


class SDKEventsBatchRequest(BaseModel):
    session_id: uuid.UUID | None = None
    tour_events: list[TourEventIn] = Field(default_factory=list)
    resolution_logs: list[ResolutionLogIn] = Field(default_factory=list)


class SDKEventsBatchResponse(BaseModel):
    ingested_tour_events: int
    ingested_resolution_logs: int

